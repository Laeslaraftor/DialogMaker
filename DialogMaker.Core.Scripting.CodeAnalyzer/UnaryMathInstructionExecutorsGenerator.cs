        protected override string EnumName => "DSharpUnaryOperator";

        protected override void GenerateExecutor(ItemModel item, SourceProductionContext context)
        {
            Generate(CreateDefaultExecutor, $"DSharp{item.Name}InstructionExecutor.g.cs", item, context);
            Generate(CreateVariableExecutor, $"DSharp{item.Name}VariableInstructionExecutor.g.cs", item, context);
            Generate(CreateFieldExecutor, $"DSharp{item.Name}FieldInstructionExecutor.g.cs", item, context);
        }

