            if (!GeneratedTypes.ContainsKey(executorName))
            {
                GeneratedTypes.Add(executorName, $"global::DialogMaker.Core.Scripting.Runtime.Executor.Bytecode.Instructions.{executorName}");
            }

            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine();
            builder.AppendLine($"using System.Runtime.CompilerServices;");
            
            if (item.Name != "Not")
            {
                builder.AppendLine($"using DialogMaker.Core.Scripting.Runtime.Numbers.MathExecutors;");
            }

            builder.AppendLine($"using DialogMaker.Core.Scripting.Runtime.Executor.TypesInfo;");
            builder.AppendLine();
            builder.AppendLine("#nullable enable");
            builder.AppendLine();
            builder.AppendLine("namespace DialogMaker.Core.Scripting.Runtime.Executor.Bytecode.Instructions");
            builder.AppendLine("{");
            builder.AppendLine($"{indent1}/// <summary>");
            builder.AppendLine($"{indent1}/// Executor of <see cref=\"DSharpBytecodeOperation.{item.Name}\"/> operation");
            builder.AppendLine($"{indent1}/// </summary>");
            builder.AppendLine($"{indent1}public sealed unsafe class {executorName} : DSharpInstructionExecutor");
            builder.AppendLine($"{indent1}{{");

            GenerateControls(builder, item, true);

            builder.AppendLine($"{indent2}#region Static");
            builder.AppendLine();
            builder.AppendLine($"{indent2}/// <summary>");
            builder.AppendLine($"{indent2}/// Global instance of <see cref=\"DSharpBytecodeOperation.{item.Name}\"/> operation executor");
            builder.AppendLine($"{indent2}/// </summary>");
            builder.AppendLine($"{indent2}public static readonly {executorName} Instance = new();");
            builder.AppendLine();
            builder.AppendLine($"{indent2}[MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder.AppendLine($"{indent2}private static void InstanceExecute(DSharpRuntimeInstruction* instruction, ref DSharpExecutionContext context)");
            builder.AppendLine($"{indent2}{{");

            if (item.Name == "Not")
            {
                builder.AppendLine($"#if DEBUG");
                builder.AppendLine($"{indent3}if (CheckStackValues(instruction, ref context, 1))");
                builder.AppendLine($"{indent3}{{");
                builder.AppendLine($"{indent4}return;");
                builder.AppendLine($"{indent3}}}");
                builder.AppendLine();
                builder.AppendLine($"{indent3}var value = context.Stack.Peek();");
                builder.AppendLine($"{indent3}var obj = value.ReadAsObject();");
                builder.AppendLine($"{indent3}var data = DSharpObject.GetData<bool>(obj);");
                builder.AppendLine();
                builder.AppendLine($"{indent3}if (obj == null || obj->Type != context.TypesProvider.Boolean)");
                builder.AppendLine($"{indent3}{{");
                builder.AppendLine($"{indent4}*context.Callback = context.ThrowExecutionException($\"Unable to invert value because it is not boolean: {{value.ValueType}}\");");
                builder.AppendLine($"{indent4}return;");
                builder.AppendLine($"{indent3}}}");
                builder.AppendLine($"#else");
                builder.AppendLine($"{indent3}var data = context.Stack.FastStructureDataPeek<bool>();");
                builder.AppendLine($"#endif");
                builder.AppendLine();
                builder.AppendLine($"{indent3}*data = !*data;");
            }
            else
            {
                builder.AppendLine($"#if DEBUG");
                builder.AppendLine($"{indent3}if (CheckStackValues(instruction, ref context, 1))");
                builder.AppendLine($"{indent3}{{");
                builder.AppendLine($"{indent4}return;");
                builder.AppendLine($"{indent3}}}");
                builder.AppendLine($"#endif");
                builder.AppendLine();
                builder.AppendLine($"{indent3}var lastValue = context.Stack.Peek();");
                builder.AppendLine($"{indent3}var obj = lastValue.ReadAsStructure();");
                builder.AppendLine($"{indent3}var data = DSharpObject.GetData(obj);");
                builder.AppendLine($"{indent3}var number = DSharpNumber.FromBufferAndType(data, obj->Type->ConverterInfo.ConvertingType);");
                builder.AppendLine();
                builder.AppendLine($"{indent3}number = DSharpNumberMathExecutor.{item.Name}(ref number);");
                builder.AppendLine($"{indent3}Unsafe.CopyBlockUnaligned(data, &number, (uint)number.Size);");

            }

            builder.AppendLine($"{indent2}}}");
            builder.AppendLine();
            builder.AppendLine($"{indent2}#endregion");
            builder.AppendLine($"{indent1}}}");
            builder.AppendLine("}");

            return builder.ToString();
        }
